#!/usr/bin/env python3
"""Fails if BarnCRMShippedPermissionSets does not name exactly the permission sets BarnCRM ships.

The Field Access Manager (C-65, ADR-0156) never offers a permission set BarnCRM ships: the
package and the access syncs (TabAccessService, ModuleAccessSyncs) manage
their access, so an edit there would be overwritten or would drift. In an installed package the
namespace already hides them; in an unpackaged install only their names do. The class holds
those names as data, generated from every package directory in sfdx-project.json, so a set
added to any package without regenerating the class fails here instead of becoming choosable.

Regenerate with:
  python3 scripts/ci/check-shipped-permission-sets.py --print > <scratch file>
then copy the scratch file over the class.
"""

import glob
import json
import os
import sys

CLASS = "packages/core/main/default/classes/BarnCRMShippedPermissionSets.cls"
SUFFIX = ".permissionset-meta.xml"


def shipped():
    with open("sfdx-project.json", encoding="utf-8") as handle:
        directories = [entry["path"] for entry in json.load(handle)["packageDirectories"]]
    names = set()
    for directory in directories:
        for path in glob.glob(os.path.join(directory, "**", "*" + SUFFIX), recursive=True):
            names.add(os.path.basename(path)[: -len(SUFFIX)])
    return sorted(names)


def render(names):
    lines = [
        "/**",
        " * Every permission set BarnCRM ships, in any package directory (C-65, ADR-0156).",
        " * The Field Access Manager never offers these: the package and the access syncs manage",
        " * their access. Generated by scripts/ci/check-shipped-permission-sets.py --print, which",
        " * also fails CI when this list and the package directories differ. Do not edit by hand.",
        " */",
        "public with sharing class BarnCRMShippedPermissionSets {",
        "\tpublic static final Set<String> NAMES = new Set<String>{",
    ]
    for index, name in enumerate(names):
        lines.append("\t\t'" + name + "'" + ("," if index < len(names) - 1 else ""))
    lines += ["\t};", "}", ""]
    return "\n".join(lines)


def main():
    names = shipped()
    expected = render(names)
    if "--print" in sys.argv[1:]:
        sys.stdout.write(expected)
        return 0
    try:
        with open(CLASS, encoding="utf-8") as handle:
            actual = handle.read()
    except FileNotFoundError:
        actual = ""
    if actual != expected:
        print(
            CLASS + ": does not match the " + str(len(names)) + " permission sets the packages"
            " ship. Regenerate it with --print (see this script's docstring)."
        )
        print("check-shipped-permission-sets.py: FAILED")
        return 1
    print("check-shipped-permission-sets.py: OK, " + str(len(names)) + " permission sets")
    return 0


if __name__ == "__main__":
    sys.exit(main())
